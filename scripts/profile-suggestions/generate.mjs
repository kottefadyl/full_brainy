// Generates the profile suggestion lists for the web app and Flutter from the *.txt sources here.
// Usage (repository root): node scripts/profile-suggestions/generate.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const lists = { occupations: 'occupation', interests: 'interest', hobbies: 'hobby' };

function read(name) {
  const rows = readFileSync(join(here, `${name}.txt`), 'utf8').split(/\r?\n/)
    .map((line) => line.trim()).filter((line) => line && !line.startsWith('#'))
    .map((line, index) => {
      const parts = line.split('|').map((part) => part.trim());
      if (parts.length !== 2 || !parts[0] || !parts[1]) throw new Error(`${name}.txt line ${index + 1}: expected "English | French"`);
      if (parts.some((part) => part.length > 60)) throw new Error(`${name}.txt: "${line}" is longer than 60 characters`);
      return parts;
    });
  for (const column of [0, 1]) {
    const seen = new Set();
    for (const row of rows) {
      const key = row[column].toLocaleLowerCase();
      if (seen.has(key)) throw new Error(`${name}.txt: duplicate "${row[column]}"`);
      seen.add(key);
    }
  }
  return rows.sort((a, b) => a[0].localeCompare(b[0], 'en'));
}

const data = Object.fromEntries(Object.keys(lists).map((name) => [name, read(name)]));
const banner = 'Generated by scripts/profile-suggestions/generate.mjs. Edit the .txt sources, not this file.';
const quoteDart = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;

const ts = [`// ${banner}`, 'export type Suggestion = readonly [en: string, fr: string];', ''];
const dart = [`// ${banner}`, '// ignore_for_file: lines_longer_than_80_chars', ''];
for (const [name, rows] of Object.entries(data)) {
  const id = `${lists[name]}Suggestions`;
  ts.push(`export const ${id}: readonly Suggestion[] = [`, ...rows.map(([en, fr]) => `  [${JSON.stringify(en)}, ${JSON.stringify(fr)}],`), '];', '');
  dart.push(`const ${id} = <(String, String)>[`, ...rows.map(([en, fr]) => `  (${quoteDart(en)}, ${quoteDart(fr)}),`), '];', '');
}
writeFileSync(join(root, 'brainy_web_app', 'lib', 'profile-suggestions.ts'), ts.join('\n'));
writeFileSync(join(root, 'brainy', 'lib', 'profile_suggestions.dart'), dart.join('\n'));
console.log(Object.entries(data).map(([name, rows]) => `${name}: ${rows.length}`).join(', '));
