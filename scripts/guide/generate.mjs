// T51: generates the in-app guide for the web app and Flutter from scripts/guide/content.mjs.
// Usage (repository root): node scripts/guide/generate.mjs
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chapters } from './content.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const icons = new Set(['compass', 'folder', 'shapes', 'pencil', 'layout', 'template', 'chart', 'boxes', 'warehouse', 'users', 'shield', 'database', 'rocket', 'briefcase']);
const ids = new Set();
for (const chapter of chapters) {
  if (ids.has(chapter.id) || !/^[a-z-]+$/.test(chapter.id)) throw new Error(`Bad or repeated chapter id ${chapter.id}`);
  ids.add(chapter.id);
  if (!icons.has(chapter.icon)) throw new Error(`Unknown icon ${chapter.icon}`);
  for (const text of [chapter.title, chapter.summary, ...chapter.sections.flatMap((section) => [section.title, section.text])]) {
    if (!text?.en?.trim() || !text?.fr?.trim()) throw new Error(`Chapter ${chapter.id}: every text needs English and French`);
  }
}
const images = [...new Set(chapters.flatMap((chapter) => chapter.sections.map((section) => section.image).filter(Boolean)))];
const missing = images.filter((name) => ['en', 'fr'].some((language) => !existsSync(join(root, 'brainy_web_app', 'public', 'guide', language, `${name}.jpg`))));
if (missing.length) console.warn(`Screenshots still to capture (scripts/guide/capture.mjs): ${missing.join(', ')}`);

const header = 'Generated by scripts/guide/generate.mjs from scripts/guide/content.mjs. Do not edit by hand.';
writeFileSync(join(root, 'brainy_web_app', 'lib', 'guide-content.ts'), `// ${header}
export type GuideText = { en: string; fr: string };
export type GuideSection = { title: GuideText; text: GuideText; image?: string };
export type GuideChapter = { id: string; icon: string; title: GuideText; summary: GuideText; sections: GuideSection[] };

export const guideChapters: GuideChapter[] = ${JSON.stringify(chapters, null, 2)};
`);

const dart = (value) => JSON.stringify(value).replace(/\$/g, '\\$');
const text = (value) => `(en: ${dart(value.en)}, fr: ${dart(value.fr)})`;
writeFileSync(join(root, 'brainy', 'lib', 'guide_content.dart'), `// ${header}
// ignore_for_file: lines_longer_than_80_chars
typedef GuideText = ({String en, String fr});
typedef GuideSection = ({GuideText title, GuideText text, String? image});
typedef GuideChapter = ({String id, String icon, GuideText title, GuideText summary, List<GuideSection> sections});

const List<GuideChapter> guideChapters = [
${chapters.map((chapter) => `  (
    id: ${dart(chapter.id)},
    icon: ${dart(chapter.icon)},
    title: ${text(chapter.title)},
    summary: ${text(chapter.summary)},
    sections: [
${chapter.sections.map((section) => `      (title: ${text(section.title)}, text: ${text(section.text)}, image: ${section.image ? dart(section.image) : 'null'}),`).join('\n')}
    ],
  ),`).join('\n')}
];
`);
console.log(`Guide: ${chapters.length} chapters, ${chapters.reduce((sum, chapter) => sum + chapter.sections.length, 0)} sections, ${images.length} screenshots.`);
